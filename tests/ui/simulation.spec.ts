test('creating a Path first and capturing its ordered points generates a module without moving the selected point into the robot', async ({ page }) => {
  const errors = observeBrowser(page);
  await openWorkspace(page);
  const emptyPath = await createPath(page);
  await expect(pathPoints(page, emptyPath)).toHaveCount(0);
  const emptyMenu = await openPathMenu(page, emptyPath, true);
  await expect(emptyMenu.getByRole('menuitem', { name: '运行', exact: true })).toBeDisabled();
  await emptyMenu.press('Escape');
  await expect(emptyMenu).toHaveCount(0);
  await expect(page.locator(`[data-object-kind="path"][data-object-id="${emptyPath}"]`)).toBeFocused();
  const first = await captureCurrent(page, emptyPath);
  const firstPose = await bodyPose(page);
  await setJoint(page, 1, 3);
  const second = await captureCurrent(page);
  const secondPose = await bodyPose(page);
  const pathId = await selectPathForPoints(page, [first, second]);
  const pathTree = page.locator(`details.object-path`).filter({ has: page.locator(`[data-object-id="${pathId}"]`) });
  await expect(pathTree.locator('[data-object-kind="target"]')).toHaveText([first.name, second.name]);
  for (const point of [first, second]) await expect(page.getByRole('button', { name: `选择目标点 ${point.name}`, exact: true })).toBeInViewport();
  const sectionLabel = page.locator('.object-section-label').filter({ hasText: '危险区域' }).locator('span');
  expect((await sectionLabel.boundingBox())!.height).toBeLessThan(25);
  await expect(page.getByRole('heading', { name: 'Path 1', exact: true })).toBeVisible();
  await selectPoint(page, first);
  await expectBodyJoints(page, [3, ...ready.slice(1)]);
  await expect(page.getByRole('textbox', { name: '目标 robtarget', exact: true })).toHaveAttribute('readonly', '');
  await expect(scene(page)).toHaveAttribute('data-selected-point-id', first.id);
  await expect.poll(async () => {
    const paths = JSON.parse((await scene(page).getAttribute('data-scene-paths'))!);
    return paths.map((path: { id: string; points: { id: string }[] }) => ({ id: path.id, ids: path.points.map(point => point.id) }));
  }).toEqual([{ id: pathId, ids: [first.id, second.id] }]);
  const rendered = JSON.parse((await scene(page).getAttribute('data-scene-paths'))!)[0];
  expect(rendered.visible).toBe(true);
  for (let i = 0; i < 2; i++) {
    for (let axis = 0; axis < 3; axis++) expect(rendered.points[i].position[axis]).toBeCloseTo([firstPose, secondPose][i].position[axis], 7);
  }
  expect(Math.hypot(...secondPose.position.map((value, i) => value - firstPose.position[i]))).toBeGreaterThan(20);
  await expectNoPointMotionActions(page);
  await expect.poll(async () => page.locator('[data-endpoint-joints]').evaluateAll(rows => rows.length > 0 && rows.every(row => ['hit', 'clear', 'uncertain'].includes(row.getAttribute('data-collision-state')!)))).toBe(true);
  await page.screenshot({ path: '/tmp/emulation-object-path.png' });
  await page.screenshot({ path: 'docs/images/workspace.png' });
  expect(await generateSource(page, pathId)).toMatch(/CONST robtarget P001/);
  await expect(moduleList(page).getByRole('option', { name: 'PATH1.modx', exact: true })).toHaveAttribute('aria-selected', 'true');
  await expect(page.getByRole('complementary', { name: '场景对象', exact: true })).toHaveCount(0);
  await expect(page.getByRole('tablist', { name: '程序编辑模式', exact: true })).toHaveCount(0);
  await expect(page.getByRole('listbox', { name: /程序指令$/ })).toHaveCount(0);
  await expect(page.getByRole('button', { name: '转为 Path', exact: true })).toHaveCount(0);
  const exported = await downloadSource(page);
  expect(exported.name).toBe('PATH1.modx');
  expect(exported.bytes.toString('utf8')).toMatch(/^MODULE PATH1\n/);
  await codeEditor(page).press('ControlOrMeta+Home');
  await expect(codeEditor(page).locator('span').filter({ hasText: /^MODULE$/ }).first()).toBeVisible();
  await page.screenshot({ path: 'docs/images/program-workspace.png' });
  expect(errors).toEqual([]);
});

test('a point exposes data and preview while the Path context menu validates and runs its recorded pose', async ({ page }) => {
  const errors = observeBrowser(page);
  await openWorkspace(page);
  const point = await captureCurrent(page);
  const storedTarget = await page.getByRole('textbox', { name: '目标 robtarget', exact: true }).inputValue();
  await setJoint(page, 1, 3);
  await selectPoint(page, point);
  await expectNoPointMotionActions(page);
  await expectBodyJoints(page, [3, ...ready.slice(1)]);
  await runPathFromMenu(page, point.pathId, { keyboard: true });
  await expect(page.locator('[data-run-phase]')).toHaveAttribute('data-run-phase', 'complete', { timeout: 20_000 });
  const target = forwardKinematics(getRobotModel('irb1100-4-0.58'), ready as [number, number, number, number, number, number]).pose;
  await expect.poll(async () => Math.hypot(...(await bodyPose(page)).position.map((value, i) => value - target.position[i]))).toBeLessThan(.01);
  await selectPoint(page, point);
  await expect(page.getByRole('textbox', { name: '目标 robtarget', exact: true })).toHaveValue(storedTarget);
  await expectNoPointMotionActions(page);
  await page.screenshot({ path: '/tmp/emulation-point-path-run.png' });
  expect(errors).toEqual([]);
});

test('joint edits keep the last valid body, block Path running on invalid input, and explicitly update an existing stored point', async ({ page }) => {
  const errors = observeBrowser(page);
  await openWorkspace(page);
  const point = await captureCurrent(page);
  await setJoint(page, 1, 3);
  await setJoint(page, 1, 1000);
  await expect(page.getByRole('alert')).toContainText('超出关节范围');
  await expectBodyJoints(page, [3, ...ready.slice(1)]);
  await expectNoPointMotionActions(page);
  await selectPath(page, point.pathId);
  await expect(page.getByRole('button', { name: '添加当前点到 Path', exact: true })).toBeDisabled();
  await page.locator(`[data-object-kind="path"][data-object-id="${point.pathId}"]`).click({ button: 'right' });
  await expect(page.getByRole('menuitem', { name: '添加当前点到 Path', exact: true })).toBeDisabled();
  await expect(page.getByRole('menuitem', { name: '运行', exact: true })).toBeDisabled();
  await page.getByRole('menu', { name: 'Path 右键菜单', exact: true }).press('Escape');
  await expect(pathPoints(page, point.pathId)).toHaveCount(1);
  await setJoint(page, 1, '');
  await expectBodyJoints(page, [3, ...ready.slice(1)]);
  await setJoint(page, 1, 6);
  await selectPoint(page, point);
  const original = await page.getByRole('textbox', { name: '目标 robtarget', exact: true }).inputValue();
  await page.getByRole('button', { name: '用当前姿态更新点', exact: true }).click();
  await expect(page.locator('[data-target-point-id]')).toHaveAttribute('data-target-point-id', point.id);
  await expect(page.getByRole('textbox', { name: '目标 robtarget', exact: true })).not.toHaveValue(original);
  await expectBodyJoints(page, [6, ...ready.slice(1)]);
  await expectNoPointMotionActions(page);
  await expect(pathPoints(page)).toHaveCount(1);
  await expect(pathPoints(page).first()).toHaveAttribute('data-object-id', point.id);
  expect(errors).toEqual([]);
});

test('Path ownership, point deletion and independent generated modules survive edits and Path deletion', async ({ page }) => {
  const errors = observeBrowser(page);
  await openWorkspace(page);
  const firstPath = await createPath(page);
  const first = await captureCurrent(page, firstPath);
  await setJoint(page, 1, 3);
  const second = await captureCurrent(page, firstPath);
  const otherPath = await createPath(page);
  await setJoint(page, 1, 6);
  const third = await captureCurrent(page, otherPath);
  await expect(pathPoints(page, firstPath)).toHaveCount(2);
  await expect(pathPoints(page, otherPath)).toHaveCount(1);
  const originalSource = await generateSource(page, firstPath);
  expect(originalSource).toContain('CONST robtarget P001');
  expect(originalSource).toContain('CONST robtarget P002');
  expect(originalSource).not.toContain('P003');
  const repeatedSource = await generateSource(page, firstPath);
  expect(repeatedSource.replace(/^MODULE \w+/, 'MODULE PATH')).toBe(originalSource.replace(/^MODULE \w+/, 'MODULE PATH'));
  await expect(moduleList(page).getByRole('option')).toHaveCount(2);
  await moduleList(page).getByRole('option', { name: 'PATH1.modx', exact: true }).click();
  expect(await readSource(page)).toBe(originalSource);

  await selectPoint(page, first);
  await pathPoints(page, firstPath).first().click({ button: 'right' });
  await page.getByRole('menuitem', { name: '删除点', exact: true }).click();
  const pointDialog = page.getByRole('dialog', { name: '删除目标点', exact: true });
  await pointDialog.getByRole('button', { name: '取消', exact: true }).click();
  await expect(pathPoints(page, firstPath)).toHaveCount(2);
  for (const point of [first, second]) {
    await page.locator(`[data-object-kind="target"][data-object-id="${point.id}"]`).click({ button: 'right' });
    await page.getByRole('menuitem', { name: '删除点', exact: true }).click();
    await pointDialog.getByRole('button', { name: '删除', exact: true }).click();
  }
  await expect(pathPoints(page, firstPath)).toHaveCount(0);
  await expect(pathObjects(page)).toHaveCount(2); // Empty Paths remain usable containers.
  await selectPath(page, firstPath);
  await expect(page.getByRole('button', { name: '转换为程序', exact: true })).toBeDisabled();
  const fourth = await captureCurrent(page, firstPath);
  expect(fourth.name).toBe('P004');
  await expect.poll(() => page.locator('[data-endpoint-joints]').count()).toBeGreaterThan(0);
  await expect.poll(async () => page.locator('[data-endpoint-joints]').evaluateAll(rows => rows.every(row => ['hit', 'clear', 'uncertain'].includes(row.getAttribute('data-collision-state')!)))).toBe(true);
  await selectPath(page, firstPath);
  await page.getByRole('button', { name: '删除 Path', exact: true }).click();
  const pathDialog = page.getByRole('dialog', { name: '删除 Path', exact: true });
  await pathDialog.getByRole('button', { name: '取消', exact: true }).click();
  await expect(pathPoints(page, firstPath)).toHaveCount(1);
  await page.getByRole('button', { name: '删除 Path', exact: true }).click();
  await pathDialog.getByRole('button', { name: '删除', exact: true }).click();
  await expect(pathObjects(page)).toHaveCount(1);
  await expect(pathPoints(page)).toHaveCount(1);
  await expect(pathPoints(page, otherPath).first()).toHaveAttribute('data-object-id', third.id);
  await expect(page.locator(`[data-object-id="${fourth.id}"]`)).toHaveCount(0);
  await selectPoint(page, third);
  await expect.poll(() => page.locator('[data-endpoint-joints]').count()).toBeGreaterThan(0);
  await openProgram(page);
  await expect(moduleList(page).getByRole('option')).toHaveCount(2);
  expect(await readSource(page)).toBe(originalSource);
  expect(errors).toEqual([]);
});

test('model switching isolates recorded programs and selections while returning restores the original points', async ({ page }) => {
  const errors = observeBrowser(page);
  await openWorkspace(page);
  const longPoint = await captureCurrent(page);
  await selectPathForPoints(page, [longPoint]);
  await page.locator(`[data-object-kind="path"][data-object-id="${longPoint.pathId}"]`).click({ button: 'right' });
  await expect(page.getByRole('menu', { name: 'Path 右键菜单', exact: true })).toBeVisible();
  await selectRobot(page, 'irb1100-4-0.475');
  await expect(page.getByRole('menu', { name: 'Path 右键菜单', exact: true })).toHaveCount(0);
  await expect(pathPoints(page)).toHaveCount(0);
  await expect(pathObjects(page)).toHaveCount(0);
  const shortPoint = await captureCurrent(page);
  expect(shortPoint.id).not.toBe(longPoint.id);
  await selectRobot(page, 'irb1100-4-0.58');
  await openScene(page);
  await expect(pathPoints(page)).toHaveCount(1);
  await expect(pathPoints(page).first()).toHaveAttribute('data-object-id', longPoint.id);
  await expect(pathPoints(page).first()).not.toHaveClass(/selected/);
  await expect(page.getByRole('heading', { name: '机器人属性', exact: true })).toBeVisible();
  await expectNoPointMotionActions(page);
  await selectRobot(page, 'irb1100-4-0.475');
  await selectRobotObject(page);
  await page.getByRole('button', { name: '机械零位', exact: true }).click();
  await expect.poll(async () => (await bodyPose(page)).position.map(value => Math.round(value))).toEqual([314, 0, 562]);
  await expect(pathPoints(page).first()).toHaveAttribute('data-object-id', shortPoint.id);
  await openScene(page);
  await page.screenshot({ path: '/tmp/emulation-object-model-scope.png' });
  expect(errors).toEqual([]);
});
